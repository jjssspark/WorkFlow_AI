-- 되돌리는 법: db/init/01_base_schema.sql의 assistant_messages 정의를 새 V파일로 옮겨
-- 다시 생성한다. 데이터는 원래 0건이라 복구할 것이 없다.
--
-- 근거: docs/trouble-shooting/2026-07-29-supabase-schema-drift.md
-- ============================================================================

