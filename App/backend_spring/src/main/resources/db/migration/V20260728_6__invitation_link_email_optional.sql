-- ============================================================================
-- 링크 공유용 초대(이메일 미지정)를 지원하기 위해 invitations.email을 nullable로 변경.
--
-- 기존 이메일 초대는 email이 특정 대상을 가리켰지만, 사이드바 "링크 복사" 기능은
-- 특정 대상 없이 팀원 역할 토큰을 발급/재사용한다. email이 NULL인 행이 그 링크
-- 초대를 나타낸다.
-- ============================================================================

ALTER TABLE invitations ALTER COLUMN email DROP NOT NULL;

COMMENT ON COLUMN invitations.email IS '이메일 지정 초대의 대상. 링크 복사로 발급된 초대는 대상이 없어 NULL';
